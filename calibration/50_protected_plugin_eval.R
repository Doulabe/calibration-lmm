# ==============================================================================
# 50_protected_plugin_eval.R
#
# Re-evaluation of the thresholds of 49_protected_plugin_v2.R at the true ratio with
# B4 = 100,000 independent draws (49: B3 = 10,000), for the 174 configurations of
# 36_calibration_enlarged.R. At 5e-8 the tails of the protected tests rest on two to six
# effective draws out of 10,000 when delta0 is near the maximizing ratio, too few to compare
# a single configuration with the nominal level.
# Thresholds are read from results/protected_plugin_v2/<config>.rds and kept fixed
#   nominal    t_{nu-1} and chi2_1 quantiles
#   plug-in    c_alpha(delta_hat(r)), delta_hat the REML estimate, interpolated on the stage-1 grid
#   protected  stage-2 threshold (B2 = 10,000 common draws) and stage-1 threshold (B1 = 1,000)
# Draws are generated by chunks of 2,500 from one stream per configuration (seed + 4,000,000),
# and size, power, Monte Carlo standard errors and effective numbers of draws are accumulated
# over the chunks.
# --check evaluates with the B3 draws of 49 instead and prints the difference with its rows.
# Usage (from the repository root):
#   nice -n 10 Rscript calibration/50_protected_plugin_eval.R [cores=3] [--check] [--only=ID,...]
# Output: results/protected_plugin_eval/<config>.rds, results/protected_plugin_eval.csv
# ==============================================================================
args   <- commandArgs(TRUE)
NCORES <- if (length(args) >= 1 && grepl("^[0-9]+$", args[1])) as.integer(args[1]) else 3L
CHECK  <- "--check" %in% args
ONLY   <- { a <- grep("^--only=", args, value = TRUE); if (length(a)) strsplit(sub("^--only=", "", a), ",")[[1]] else NULL }
Sys.setenv(OMP_NUM_THREADS = "1", OPENBLAS_NUM_THREADS = "1", VECLIB_MAXIMUM_THREADS = "1")
source("calibration/00_functions.R")
suppressPackageStartupMessages(library(parallel))
B3 <- 10000L; B4 <- 100000L; CH2 <- 2500L
GRID2 <- c(0, 10^seq(-4, 4, length.out = 81))          # estimation grid of 36
AL    <- c(1e-3, 1e-5, 5e-8)
UG    <- seq(-10, 15, by = 0.025)                       # u grid for the LR (as 49)

pick_grid <- function(O, grid) {                          # as in 36
  g <- max.col(O, ties.method = "first"); dh <- grid[g]
  int <- g > 2 & g < length(grid)
  if (any(int)) {
    ii <- which(int); lg <- log(grid)
    x1 <- lg[g[ii] - 1]; x2 <- lg[g[ii]]; x3 <- lg[g[ii] + 1]
    f1 <- O[cbind(ii, g[ii] - 1)]; f2 <- O[cbind(ii, g[ii])]; f3 <- O[cbind(ii, g[ii] + 1)]
    den <- (x2 - x1) * (f2 - f3) - (x2 - x3) * (f2 - f1)
    num <- (x2 - x1)^2 * (f2 - f3) - (x2 - x3)^2 * (f2 - f1)
    xs <- ifelse(abs(den) > 1e-14, x2 - 0.5 * num / den, x2)
    dh[ii] <- exp(pmin(pmax(xs, x1), x3))
  }
  dh
}
